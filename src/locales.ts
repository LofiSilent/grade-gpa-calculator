export const messages: Record<Locale, Messages> = { en, ru, kk };
export type MessageKey = Exclude<keyof Messages, "exampleNames">;
export function translate(
  locale: Locale,
  key: MessageKey,
  params: Record<string, string | number> = {},
) {
  return messages[locale][key].replace(/\{(\w+)\}/g, (_match, key: string) =>
    String(params[key] ?? `{${key}}`),
  );
}
export function loadLocale(): Locale {
  try {
    const saved = localStorage.getItem("grade-language");
    if (saved === "ru" || saved === "kk" || saved === "en") return saved;
  } catch {}
  return "ru";
}
export function localizedDecimal(value: string, locale: Locale) {
  return locale === "en" ? value : value.replace(".", ",");
}
